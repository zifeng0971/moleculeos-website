/**
 * Extracts compact Cα traces from the demo structures for the homepage capability illustrations.
 * Output: content/task-structures.json (centred, unit-scaled coordinates + per-residue metadata).
 * Run: npx tsx scripts/prepare-task-structures.ts
 */
import fs from 'node:fs';
import path from 'node:path';

type Residue = { chain: string; seq: number; aa: string; x: number; y: number; z: number; b: number };

const THREE_TO_ONE: Record<string, string> = {
  ALA: 'A', ARG: 'R', ASN: 'N', ASP: 'D', CYS: 'C', GLN: 'Q', GLU: 'E', GLY: 'G', HIS: 'H', ILE: 'I',
  LEU: 'L', LYS: 'K', MET: 'M', PHE: 'F', PRO: 'P', SER: 'S', THR: 'T', TRP: 'W', TYR: 'Y', VAL: 'V',
};

function readCalpha(file: string): Residue[] {
  const lines = fs.readFileSync(file, 'utf8').split('\n');
  const header: string[] = [];
  const residues: Residue[] = [];
  let inLoop = false;
  for (const raw of lines) {
    const line = raw.trim();
    if (line.startsWith('_atom_site.')) { header.push(line.slice('_atom_site.'.length)); inLoop = true; continue; }
    if (!inLoop || !header.length) continue;
    if (line === '#' || line.startsWith('loop_') || line.startsWith('_')) { if (residues.length) break; continue; }
    const cols = line.split(/\s+/);
    const get = (name: string) => cols[header.indexOf(name)];
    if (get('group_PDB') !== 'ATOM' || get('label_atom_id') !== 'CA') continue;
    if (get('pdbx_PDB_model_num') && get('pdbx_PDB_model_num') !== '1') continue;
    const alt = get('label_alt_id');
    if (alt && alt !== '.' && alt !== 'A') continue;
    residues.push({
      chain: get('auth_asym_id') ?? get('label_asym_id'), seq: Number(get('auth_seq_id')),
      aa: THREE_TO_ONE[get('label_comp_id')] ?? 'X',
      x: Number(get('Cartn_x')), y: Number(get('Cartn_y')), z: Number(get('Cartn_z')), b: Number(get('B_iso_or_equiv')),
    });
  }
  return residues;
}

function normalise(residues: Residue[]) {
  const n = residues.length;
  const c = residues.reduce((acc, r) => [acc[0] + r.x / n, acc[1] + r.y / n, acc[2] + r.z / n], [0, 0, 0]);
  const radius = Math.max(...residues.map(r => Math.hypot(r.x - c[0], r.y - c[1], r.z - c[2])));
  const bs = residues.map(r => r.b), bMin = Math.min(...bs), bMax = Math.max(...bs);
  return residues.map(r => ({
    chain: r.chain, aa: r.aa,
    p: [(r.x - c[0]) / radius, (r.y - c[1]) / radius, (r.z - c[2]) / radius].map(v => Math.round(v * 1000) / 1000),
    // Relative flexibility 0–1 from crystallographic B-factors (illustrative only).
    flex: bMax > bMin ? Math.round((r.b - bMin) / (bMax - bMin) * 100) / 100 : 0,
  }));
}

/** Residues whose Cα lies within `cutoff` Å of any Cα on a different chain. */
function interfaceIndices(residues: Residue[], cutoff = 9) {
  const out: number[] = [];
  residues.forEach((a, i) => {
    if (residues.some(b => b.chain !== a.chain && Math.hypot(a.x - b.x, a.y - b.y, a.z - b.z) < cutoff)) out.push(i);
  });
  return out;
}

const root = process.cwd();
const petase = readCalpha(path.join(root, 'public/demo/5xh3.cif'));
const complex = readCalpha(path.join(root, 'public/demo/antibody-affinity/workbench.cif'));
const output = {
  _source: 'Generated by scripts/prepare-task-structures.ts from public/demo/5xh3.cif and antibody-affinity/workbench.cif',
  petase: normalise(petase),
  complex: { residues: normalise(complex), interface: interfaceIndices(complex) },
};
fs.writeFileSync(path.join(root, 'content/task-structures.json'), JSON.stringify(output));
console.log(`PETase ${petase.length} residues; complex ${complex.length} residues (${output.complex.interface.length} at interface).`);
