"""
Converts the native MOS MMetrics capture for the case-01 complex (PD-L1 chain A + KN035 VHH chain B, MMFold_1; website-cases/pdl1/02-mmetrics-kn035)
into the shape the homepage MMetrics demo renders (same shape as content/mmetrics-5grj.json). Values are the native ones: description, reasoning,
CDR ranges per scheme, paratope / epitope, typed interaction records. The Antibody Design cards list the heavy-chain files only (a VHH has no light chain).
Run: python3 scripts/prepare-mmetrics-kn035.py
"""
import json, re, collections
W = 'website-cases/pdl1/02-mmetrics-kn035/'
res = json.load(open(W + 'results.json'))
homolog_cards = json.load(open(W + 'reruns/20261029/raw/homologs-ui-cards.json'))
homologs = {
    'method': 'Searched by antigen sequence similarity',
    'items': [
        {'id': lines[0], 'type': lines[1], 'identity': float(lines[2].rstrip('%'))}
        for card in homolog_cards
        for lines in [card['text'].splitlines()]
    ],
}
rerun_record = json.load(open(W + 'reruns/20261029/raw/mos-export/kn035_case02/raw/mmetrics_345489060729856/record.json'))
desc = rerun_record['classification']['description']
reasoning = rerun_record['classification']['reasoning']

fasta = open(W + 'raw/master-sequences.fasta').read().split('>')[1:]
seqs = {}
for block in fasta:
    head, *body = block.splitlines(); seqs[head.strip()[0] if head.strip()[:1] in 'AB' else head.strip()] = ''.join(body).strip()
if 'A' not in seqs: seqs = {k[-1]: v for k, v in seqs.items()}
chains = [{'id': 'A', 'fragment': None, 'sequence': seqs['A']}, {'id': 'B', 'fragment': 'VHH', 'sequence': seqs['B']}]

THREE = {'A': 'ALA', 'R': 'ARG', 'N': 'ASN', 'D': 'ASP', 'C': 'CYS', 'Q': 'GLN', 'E': 'GLU', 'G': 'GLY', 'H': 'HIS', 'I': 'ILE', 'L': 'LEU', 'K': 'LYS', 'M': 'MET', 'F': 'PHE', 'P': 'PRO', 'S': 'SER', 'T': 'THR', 'W': 'TRP', 'Y': 'TYR', 'V': 'VAL'}
residue = lambda chain, n: {'id': f'{chain}:{n}', 'label': f'{chain}:{THREE[seqs[chain][n - 1]]}{n}'}
epitope = [residue('A', n) for n in res['epitope']['label_seq_ids']]
paratope = [residue('B', n) for n in res['paratope']['label_seq_ids']]
cdr = {scheme: [{'chain': 'B', 'from': r['start'], 'to': r['end'], 'name': re.match(r'(H-CDR\d)', r['name']).group(1)} for r in rows] for scheme, rows in res['CDR_by_scheme'].items()}

PROP = {}
for n in 'GLY VAL PRO ILE LEU ALA'.split(): PROP[n] = 'Aliphatic'
for n in 'SER THR ASN GLN'.split(): PROP[n] = 'Polar'
for n in 'TYR PHE TRP'.split(): PROP[n] = 'Aromatic'
for n in 'GLU ASP'.split(): PROP[n] = 'Acidic'
for n in 'ARG LYS HIS'.split(): PROP[n] = 'Basic'
PROP['MET'] = 'Sulfur'; PROP['CYS'] = 'Sulfur'
rows = json.load(open(W + 'raw/native-ui/interactions.json'))['rows'][1:]
def node(label):
    m = re.match(r'([A-Z]):([A-Z]{3})(\d+)$', label)
    return {'key': f'{m.group(2)}{m.group(3)}.{m.group(1)}', 'name': m.group(2), 'number': int(m.group(3)), 'chain': m.group(1), 'property': PROP.get(m.group(2), 'Polar')}
left, right, links = {}, {}, []
for kind, ra, rb, dist in rows:
    a, b = node(ra), node(rb)
    left.setdefault(a['key'], a); right.setdefault(b['key'], b)
    links.append({'a': a['key'], 'b': b['key'], 'category': kind, 'distance': float(dist)})
interactions = [{'key': 'A:B', 'a': 'A', 'b': 'B', 'left': sorted(left.values(), key=lambda n: n['number']), 'right': sorted(right.values(), key=lambda n: n['number']), 'links': links}]

out = {
    '_source': 'Generated by scripts/prepare-mmetrics-kn035.py from the native MOS MMetrics capture of the KN035 case (website-cases/pdl1/02-mmetrics-kn035): PD-L1 chain A + KN035 VHH chain B, MMFold_1.',
    'id': 'KN035', 'name': 'PD-L1 + KN035', 'src': '/demo/kn035-pdl1-mmfold.cif', 'chains': chains,
    'description': {'category': 'Antigen–Antibody', 'confidence': 'high', 'text': desc, 'reasoning': reasoning},
    'homologs': homologs,
    'cdr': cdr, 'paratope': paratope, 'epitope': epitope, 'extraGroups': [],
    'interactions': interactions,
    'mutationScoring': ['MutXevo.csv', 'MutXstruct.csv', 'MutXseq.csv', 'MutXaff.csv'],
    'antibodyDesign': ['AbScN_heavy..csv', 'AbAn_heavy.csv', 'ParaDt_heavy.csv'],
}
json.dump(out, open('content/mmetrics-kn035.json', 'w'), ensure_ascii=False, indent=1)
print(len(epitope), len(paratope), {k: len(v) for k, v in cdr.items()}, len(links), collections.Counter(l['category'] for l in links), {c['id']: len(c['sequence']) for c in chains})
