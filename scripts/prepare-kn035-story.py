"""
Builds the data behind the single-protein homepage waterfall (PD-L1 + KN035, MMFold_1 from case 01).
  content/kn035-story.json        compact per-step numbers and residue lists (all residue ids are MMFold_1 chain + label_seq_id)
  public/demo/kn035-pdl1-story.cif  MMFold_1 (chains A, B) plus three de novo binders, already aligned onto PD-L1 chain A, as chains C, D, E
Nothing is invented: every value is copied from website-cases/pdl1/{02..05}-*-kn035 results. Run: python3 scripts/prepare-kn035-story.py
"""
import json, re, collections
W = 'website-cases/pdl1/'
J = lambda p: json.load(open(W + p))

# ---- 02: interface -------------------------------------------------------------------------------------------------
res02 = J('02-mmetrics-kn035/residues-on-mmfold1.json')['residues']
by = collections.defaultdict(set)
for r in res02: by[(r['chain'], r['group'])].add(r['label_seq_id'])
epitope = sorted(by[('A', 'epitope')]); paratope = sorted(by[('B', 'paratope')])
cdr = {f'CDR{i}': sorted(by[('B', f'CDR_IMGT_{i}')]) for i in (1, 2, 3)}
net_a = sorted(by[('A', 'interaction_network')]); net_b = sorted(by[('B', 'interaction_network')])

# ---- 03: affinity --------------------------------------------------------------------------------------------------
r03 = J('03-affinity-kn035/results.json')
cand03 = {c['mutation']: c for c in J('03-affinity-kn035/raw/candidates-all-chain-B.json')}
vm = {v['mutation']: v for v in r03['variant_models']}
affinity = []
for m in ('V109L', 'Q116M', 'T105L'):
    c, v = cand03[m], vm[m]
    affinity.append({
        'mutation': m, 'chain': 'B', 'pos': c['label_seq_id'], 'wt': c['wild_type'], 'mut': c['mutant'], 'ddg': round(c['ddG_pred'], 2),
        'facing': c['PDL1_residues_facing_WT_at_4_5_A'], 'iptm': round(v['best_confidence_raw']['iptm'], 3), 'plddt': round(v['best_confidence_raw']['plddt'], 1),
        'samples': v['sample_count'], 'task': v['task_id'],
    })

# ---- 04: developability ---------------------------------------------------------------------------------------------
r04 = J('04-developability-kn035/results.json')
x04 = {r['mutation']: r for r in J('04-developability-kn035/affinity-candidates-x-developability.json')['rows']}
cross = []
for m in ('V109L', 'Q116M', 'T105L'):
    r = x04[m]; s = r['scores']
    cross.append({'mutation': m, 'ddg': round(r['ddG_pred'], 2), 'struct': round(s['structural_fitness']['delta_vs_WT_at_same_position'], 2),
                  'seq': round(s['sequence_fitness']['delta_vs_WT_at_same_position'], 2), 'evo': round(s['evolutionary_fitness']['delta_vs_WT_at_same_position'], 2),
                  'risk': [k for _, k in r['local_risk_motifs_added']]})
framework = []
for c in r04['framework_candidates']:
    n = c['screen_notes']
    framework.append({'mutation': c['mutation'], 'pos': c['label_seq_id'], 'struct': round(float(n['stability_delta']), 2), 'seq': round(float(n['seq_fitness_delta']), 2),
                      'evo': round(float(n['evolutionary_delta']), 2), 'risk': n['risk_flags'], 'paratopeDist': round(float(n['nearest_paratope_dist_A']), 1)})
protected = r04['protected_positions']; disulfides = r04['protected_disulfide_pairs']

# ---- 05: de novo ----------------------------------------------------------------------------------------------------
rows = {r['seed']: r for r in J('05-denovo-kn035/round-comparison.json')['rows']}
cands = {c['seed']: c for c in J('05-denovo-kn035/results.json')['candidates'] + J('05-denovo-kn035/round2/results.json')['candidates']}
PICK = [(333, 'C', '05-denovo-kn035/raw/local/seed333_target_A_aligned.cif'), (555, 'D', '05-denovo-kn035/round2/raw/local/seed555_target_A_aligned.cif'),
        (444, 'E', '05-denovo-kn035/round2/raw/local/seed444_target_A_aligned.cif')]
hot = [h['label_seq_id'] for h in cands[333]['hotspot_distances']]
designs = []
for seed, chain, _ in PICK:
    r, c = rows[seed], cands[seed]
    designs.append({'seed': seed, 'chain': chain, 'len': r['binder_length'], 'ala': round(r['Ala_fraction'], 3), 'bsa': round(r['BSA_A2']), 'epitope': r['epitope_contact_count_4_5_A'],
                    'epitopeTotal': r['epitope_total'], 'hotspots': r['hotspots_contacted_4_5_A'], 'hotspotTotal': r['hotspot_count'], 'rmsd': round(r['target_CA_RMSD_A'], 2),
                    'sequence': r['designed_sequence'], 'contacts': c['local_interface_metrics']['target_contact_label_seq_ids'], 'task': r['task_id']})

story = {
    '_source': 'Generated by scripts/prepare-kn035-story.py from website-cases/pdl1/{02..05}-*-kn035. Residue ids are MMFold_1 chain + label_seq_id.',
    'master': {'file': '/demo/kn035-pdl1-story.cif', 'iptm': round(r03['master_confidence_raw']['iptm'], 3), 'plddt': round(r03['master_confidence_raw']['plddt'], 1), 'lenA': 118, 'lenB': 128},
    'interface': {'epitope': epitope, 'paratope': paratope, 'cdr': cdr, 'contactsA': net_a, 'contactsB': net_b, 'contacts': 44},
    'affinity': {'candidates': affinity, 'scanRows': r03['chain_B_substitution_rows']},
    'developability': {'protected': protected, 'disulfides': disulfides, 'cross': cross, 'framework': framework},
    'denovo': {'hotspots': hot, 'designs': designs},
}

# ---- structure bundle -----------------------------------------------------------------------------------------------
COLS = ['group_PDB', 'id', 'type_symbol', 'label_atom_id', 'label_alt_id', 'label_comp_id', 'label_asym_id', 'label_entity_id', 'label_seq_id', 'pdbx_PDB_ins_code',
        'Cartn_x', 'Cartn_y', 'Cartn_z', 'occupancy', 'B_iso_or_equiv', 'auth_seq_id', 'auth_asym_id', 'pdbx_PDB_model_num']

def atoms(path, keep):
    lines = open(path).read().splitlines()
    cols = [l.split('.')[1] for l in lines if l.startswith('_atom_site.')]
    out = []
    for l in lines:
        if not l.startswith(('ATOM', 'HETATM')): continue
        d = dict(zip(cols, l.split()))
        if d['label_asym_id'] in keep: out.append(d)
    return out

rows_out, serial = [], 0
def emit(d, chain, entity):
    global serial
    serial += 1
    seq = d['label_seq_id']
    rows_out.append(f"ATOM {serial} {d['type_symbol']} {d['label_atom_id']} . {d['label_comp_id']} {chain} {entity} {seq} ? {d['Cartn_x']} {d['Cartn_y']} {d['Cartn_z']} {d.get('occupancy','1')} {d.get('B_iso_or_equiv','0')} {d.get('auth_seq_id', seq)} {chain} 1")

for d in atoms('public/demo/kn035-pdl1-mmfold.cif', {'A', 'B'}): emit(d, d['label_asym_id'], 1 if d['label_asym_id'] == 'A' else 2)
for k, (seed, chain, path) in enumerate(PICK):
    # In the aligned design files chain A is the new binder; chain B is PD-L1 (already superposed on MMFold_1 chain A).
    for d in atoms(W + path, {'A'}): emit(d, chain, 3 + k)
head = ['data_kn035_pdl1_story', '#', 'loop_'] + [f'_atom_site.{c}' for c in COLS]
open('public/demo/kn035-pdl1-story.cif', 'w').write('\n'.join(head + rows_out) + '\n')
def ca_points(path):
    return [round(float(d[k]), 2) for d in atoms(W + path, {'A'}) if d['label_atom_id'] == 'CA' for k in ('Cartn_x', 'Cartn_y', 'Cartn_z')]
for design, (_, _, path) in zip(designs, PICK): design['ca'] = ca_points(path)

json.dump(story, open('content/kn035-story.json', 'w'), ensure_ascii=False, separators=(',', ':'))
print('story ok:', len(rows_out), 'atoms;', {d['chain']: d['len'] for d in designs}, 'epitope', len(epitope), 'paratope', len(paratope))
