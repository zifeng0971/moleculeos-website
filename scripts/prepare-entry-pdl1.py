#!/usr/bin/env python3
"""Builds the homepage hero case (PD-L1 + KN035, natural-language entry) from website-cases/pdl1/00-entry.

Writes content/entry-pdl1.json and public/demo/kn035-pdl1-entry.cif. Scores and the interface lists are the MOS agent's
own output (final reply); the 5JDS comparison counts are the agent's, not recomputed here.
"""
import json, shutil
from pathlib import Path

root = Path(__file__).resolve().parent.parent
case = root / 'website-cases/pdl1/00-entry'
res = json.loads((case / 'results.json').read_text())
inp = json.loads((case / 'input.json').read_text())

sel = next(s for s in res['samples'] if s['sample'] == res['selected_sample'])
shutil.copyfile(case / sel['cif'], root / 'public/demo/kn035-pdl1-entry.cif')

iface = res['agent_interface']
# Model index -> UniProt numbering on PD-L1 is n + 16 (agent report), so the pairs below are written in UniProt and drawn by model index.
pairs = [
    {'a': 'Tyr56', 'aId': 40, 'b': 'Phe101', 'bId': 101, 'kind': 'stack'},
    {'a': 'Glu58', 'aId': 42, 'b': 'Ser100', 'bId': 100, 'kind': 'hbond'},
    {'a': 'Asp61', 'aId': 45, 'b': 'Ser30', 'bId': 30, 'kind': 'hbond'},
    {'a': 'Gln66', 'aId': 50, 'b': 'Asp103', 'bId': 103, 'kind': 'hbond'},
    {'a': 'Arg113', 'aId': 97, 'b': 'Asp99', 'bId': 99, 'kind': 'salt'},
    {'a': 'Arg125', 'aId': 109, 'b': 'Gln116', 'bId': 116, 'kind': 'hbond'},
]
out = {
    '_source': 'Generated by scripts/prepare-entry-pdl1.py from website-cases/pdl1/00-entry. Residue ids are model indices (A: UniProt n-16; B: from Q1).',
    # The structure is already on screen when the demo opens, so the prompt asks for the interface analysis, not a prediction.
    'prompt': 'Analyze the binding interface between human PD-L1 (chain A) and the nanobody KN035 (chain B), and tell me which residues form it.',
    'chains': [{'id': c['id'], 'role': c['role'], 'length': c['length'], 'sequence': c['sequence']} for c in inp['chains']],
    'structure': '/demo/kn035-pdl1-entry.cif',
    'projectId': res['project_id'], 'taskId': res['task_id'],
    'samples': [{'n': s['sample'], 'iptm': round(s['iptm'], 2), 'ptm': round(s['ptm'], 2), 'plddt': round(s['plddt'], 1), 'selected': s['sample'] == res['selected_sample']} for s in res['samples']],
    'interface': {'epitope': iface['A']['model_label_seq_ids'], 'paratope': iface['B']['positions']},
    'summary': {'bsa': 1419, 'bsaA': 699, 'bsaB': 721, 'hbonds': 13, 'salt': 1, 'stack': 1, 'epitopeTotal': 19, 'paratopeTotal': 21},
    'vs5JDS': {'epitope': [18, 19], 'paratope': [18, 18]},
    'pairs': pairs,
}
(root / 'content/entry-pdl1.json').write_text(json.dumps(out, ensure_ascii=False, indent=2) + '\n')
print('ok', len(out['interface']['epitope']), len(out['interface']['paratope']))
