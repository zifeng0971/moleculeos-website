"""
Converts the native MOS MMetrics capture for PD-L1 + avelumab (5GRJ, website-cases/pdl1/02-mmetrics) into the shape the
homepage MMetrics demo renders (same shape as content/mmetrics-4ht1.json). Nothing is invented: description, annotations,
interaction records, CDR ranges (from the native AbAn CSVs) and file names are the native values. The UniProt "Feature"
group (C:ARG221) is left out: that residue has no coordinates in the structure.
Run: python3 scripts/prepare-mmetrics-5grj.py
"""
import json, re, collections
N = 'website-cases/pdl1/02-mmetrics/raw/native-ui/'
res = json.load(open('website-cases/pdl1/02-mmetrics/results.json'))
panel = json.load(open(N + 'panel-dom.json'))
html = panel['html']
text = lambda cls: re.search(r'class="%s[^"]*">(.*?)</div>' % cls, html, re.S).group(1)
desc = re.sub(r'<[^>]+>', '', re.search(r'class="desc___[^"]*">(.*?)</div>', html, re.S).group(1)).strip()
reasoning = re.sub(r'<[^>]+>', '', re.search(r'class="reasoning___[^"]*">(.*?)</div>', html, re.S).group(1)).replace('Reasoning', '', 1).strip()

chains = [
    {'id': 'A', 'fragment': 'VH', 'sequence': next(c['entity_sequence'] for c in res['chains'] if c['mos_chain'] == 'A')},
    {'id': 'B', 'fragment': 'VL', 'sequence': next(c['entity_sequence'] for c in res['chains'] if c['mos_chain'] == 'B')},
    {'id': 'C', 'fragment': None, 'sequence': next(c['entity_sequence'] for c in res['chains'] if c['mos_chain'] == 'C')},
]

# CDR ranges per numbering scheme, from the native AbAn CSVs mapped to structure numbering.
numbering = json.load(open(N + 'verified-antibody-csv-numbering.json'))
cdr = {}
for scheme, key in (('IMGT', 'region_imgt'), ('Kabat', 'region_kabat'), ('Chothia', 'region_chothia')):
    out = []
    for chain, tag in (('A', 'H'), ('B', 'L')):
        rows = [r for r in numbering if r['chain'] == chain]
        cur = None
        for r in rows:
            reg = r[key]
            if reg.startswith('CDR'):
                if cur and cur['name'] == f"{tag}-{reg}" and r['label_seq_id'] == cur['to'] + 1: cur['to'] = r['label_seq_id']
                else:
                    cur = {'chain': chain, 'from': r['label_seq_id'], 'to': r['label_seq_id'], 'name': f"{tag}-{reg}"}; out.append(cur)
            else: cur = None
    cdr[scheme] = out

ann = json.load(open(N + 'annotations.json'))
THREE = {'ALA':'A','ARG':'R','ASN':'N','ASP':'D','CYS':'C','GLN':'Q','GLU':'E','GLY':'G','HIS':'H','ILE':'I','LEU':'L','LYS':'K','MET':'M','PHE':'F','PRO':'P','SER':'S','THR':'T','TRP':'W','TYR':'Y','VAL':'V'}
def residue(label):
    m = re.match(r'([A-Z]):([A-Z]{3})(\d+)$', label); return {'id': f'{m.group(1)}:{m.group(3)}', 'label': label}
paratope = [residue(i['label']) for i in ann[0]['items']]
epitope = [residue(i['label']) for i in ann[1]['items']]
domain = []
for i in ann[2]['items']:
    m = re.match(r'([A-Z]):(\d+)-(\d+)$', i['label']); domain.append({'chain': m.group(1), 'from': int(m.group(2)), 'to': int(m.group(3)), 'label': f"{m.group(1)}:{m.group(2)}–{m.group(3)}"})
ptm = [residue(i['label']) for i in ann[3]['items']]

# Interactions: residue property classes follow the native plot's node colours.
PROP = {}
for n in 'GLY VAL PRO ILE LEU ALA'.split(): PROP[n] = 'Aliphatic'
for n in 'SER THR ASN GLN'.split(): PROP[n] = 'Polar'
for n in 'TYR PHE TRP'.split(): PROP[n] = 'Aromatic'
for n in 'GLU ASP'.split(): PROP[n] = 'Acidic'
for n in 'ARG LYS HIS'.split(): PROP[n] = 'Basic'
PROP['MET'] = 'Sulfur'
recs = json.load(open(N + 'interactions.json'))
pairs = collections.OrderedDict()
def node(label):
    m = re.match(r'([A-Z]):([A-Z]{3})(\d+)$', label)
    return {'key': f'{m.group(2)}{m.group(3)}.{m.group(1)}', 'name': m.group(2), 'number': int(m.group(3)), 'chain': m.group(1), 'property': PROP.get(m.group(2), 'Polar')}
for r in recs:
    p = pairs.setdefault(r['chain_pair'], {'key': r['chain_pair'], 'a': r['chain_pair'][0], 'b': r['chain_pair'][2], 'left': {}, 'right': {}, 'links': []})
    a, b = node(r['residue_a']), node(r['residue_b'])
    p['left'].setdefault(a['key'], a); p['right'].setdefault(b['key'], b)
    p['links'].append({'a': a['key'], 'b': b['key'], 'category': {'π-π Stack': 'π-π Stack'}.get(r['type'], r['type']), 'distance': r['distance_A']})
interactions = []
for p in pairs.values():
    interactions.append({**p, 'left': sorted(p['left'].values(), key=lambda n: n['number']), 'right': sorted(p['right'].values(), key=lambda n: n['number'])})

out = {
    '_source': 'Generated by scripts/prepare-mmetrics-5grj.py from the native MOS MMetrics capture of PDL1-02-MMetrics-20261020 (5GRJ: avelumab VH/VL + human PD-L1).',
    'id': '5GRJ', 'name': '5GRJ', 'src': '/demo/5grj-avelumab-pdl1.cif', 'chains': chains,
    'description': {'category': 'Antigen–Antibody', 'confidence': 'high', 'text': desc, 'reasoning': reasoning},
    'homologs': {'method': 'Searched by antigen sequence similarity', 'items': [], 'empty': 'No significant homologs found.'},
    'cdr': cdr, 'paratope': paratope, 'epitope': epitope,
    'extraGroups': [{'title': 'Domain', 'unit': 'uniprot', 'ranges': domain}, {'title': 'PTM', 'unit': 'uniprot', 'residues': ptm}],
    'interactions': interactions,
    'mutationScoring': ['MutXevo.csv', 'MutXstruct.csv', 'MutXseq.csv', 'MutXaff.csv'],
    'antibodyDesign': ['AbScN_heavy..csv', 'AbScN_light.csv', 'AbAn_heavy.csv', 'AbAn_light.csv', 'ParaDt_heavy.csv', 'ParaDt_light.csv'],
}
json.dump(out, open('content/mmetrics-5grj.json', 'w'), ensure_ascii=False, indent=1)
print({k: (len(v) if hasattr(v, '__len__') else v) for k, v in out.items()}, {k: len(v) for k, v in cdr.items()}, [len(p['links']) for p in interactions])
print(cdr['IMGT'])
