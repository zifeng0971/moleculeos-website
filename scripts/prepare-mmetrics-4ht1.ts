/**
 * Converts the MOS MMetrics record for 4HT1 (TWEAK + rabbit Fv, predicted model sample 2) into the shape the homepage
 * MMetrics demo renders. Inputs were exported from the user's MOS project: public/demo/4ht1.cif and
 * content/mmetrics-4ht1.record.json. Residue names are read from the structure, not inferred.
 * Run: npx tsx scripts/prepare-mmetrics-4ht1.ts
 */
import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const record = JSON.parse(fs.readFileSync(path.join(root, 'content/mmetrics-4ht1.record.json'), 'utf8'));

// Residue names by chain + author number, from the CIF.
const header: string[] = [];
const names = new Map<string, string>();
for (const line of fs.readFileSync(path.join(root, 'public/demo/4ht1.cif'), 'utf8').split('\n')) {
  if (line.startsWith('_atom_site.')) { header.push(line.trim().slice('_atom_site.'.length)); continue; }
  if (!line.startsWith('ATOM')) continue;
  const c = line.trim().split(/\s+/), get = (n: string) => c[header.indexOf(n)];
  names.set(`${get('auth_asym_id')}:${get('auth_seq_id')}`, get('label_comp_id'));
}
const residue = (chain: string, n: number) => ({ id: `${chain}:${n}`, label: `${chain}:${names.get(`${chain}:${n}`) ?? 'UNK'}${n}` });

const entities = record.protein_metadata.entities as { entity_id: number; chain_id: string[]; sequence: string; antibody_fragment?: string }[];
const features = record.annotations.features as { entity_id: number; annotation_type: string; annotation_source: string; range?: number[][]; loc?: number[]; evidence: string }[];

const cdr: Record<string, { chain: string; from: number; to: number; name: string }[]> = {};
for (const f of features.filter(f => f.annotation_type === 'cdr')) {
  const chain = /chain (\w)/.exec(f.evidence)![1];
  for (const [from, to] of f.range!) (cdr[f.annotation_source] ??= []).push({ chain, from, to, name: f.evidence.split(' ')[0] });
}
const site = (type: string) => features.filter(f => f.annotation_type === type).flatMap(f => {
  const chain = type === 'epitope' ? 'C' : /chain (\w)/.exec(f.evidence)![1];
  return f.loc!.map(n => residue(chain, n));
}).filter((r, i, all) => all.findIndex(x => x.id === r.id) === i);

const homology = record.annotations.homology as { hit_id: string; identity_percentage: number }[];
const output = {
  _source: 'Generated by scripts/prepare-mmetrics-4ht1.ts from the MOS MMetrics record of 4HT1_TWEAK_rabbit_Fv_complex_sample2 (exported from the user\'s MOS project).',
  id: '4HT1',
  name: '4HT1_TWEAK_rabbit_Fv_complex_sample2',
  src: '/demo/4ht1.cif',
  chains: entities.map(e => ({ id: e.chain_id[0], fragment: e.antibody_fragment ?? null, sequence: e.sequence })),
  description: { category: 'Antigen–Antibody', confidence: record.classification.confidence, text: record.classification.description, reasoning: record.classification.reasoning },
  homologs: {
    method: 'Searched by antigen sequence similarity',
    items: homology.map(h => {
      const [db, id] = h.hit_id.split('|');
      return { id: id.replace(/\.\d+$/, ''), type: db === 'pdb' ? 'Crystal' : null, identity: Math.round(h.identity_percentage * 1000) / 10 };
    }),
  },
  cdr,
  paratope: site('paratope'),
  epitope: site('epitope'),
  interactions: (record.interactions['2d_plot_data'] as { interaction_key: string; residues_a: { key: string; name: string; number: number; chain: string; property_type: string }[]; residues_b: typeof record.interactions['2d_plot_data'][0]['residues_a']; interactions: { residue_key_a: string; residue_key_b: string; category: string; distance: number }[] }[]).map(p => {
    const node = (r: { key: string; name: string; number: number; chain: string; property_type: string }) => ({ key: r.key, name: r.name, number: r.number, chain: r.chain, property: r.property_type });
    return { key: p.interaction_key, a: p.interaction_key.split(':')[0], b: p.interaction_key.split(':')[1], left: p.residues_a.map(node), right: p.residues_b.map(node), links: p.interactions.map(i => ({ a: i.residue_key_a, b: i.residue_key_b, category: i.category, distance: i.distance })) };
  }),
  mutationScoring: ['MutXevo.csv', 'MutXstruct.csv', 'MutXseq.csv'],
  antibodyDesign: ['AbScN_heavy.csv', 'AbScN_light.csv', 'AbAn_heavy.csv', 'AbAn_light.csv', 'ParaDt_heavy.csv', 'ParaDt_light.csv'],
};
fs.writeFileSync(path.join(root, 'content/mmetrics-4ht1.json'), JSON.stringify(output, null, 1));
console.log(`chains ${output.chains.map(c => c.id).join(',')}; paratope ${output.paratope.length}; epitope ${output.epitope.length}; pairs ${output.interactions.map(i => `${i.key}(${i.links.length})`).join(' ')}; cdr ${Object.keys(cdr).join('/')}`);
